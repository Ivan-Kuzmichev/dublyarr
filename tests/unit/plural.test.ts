import { expect, test } from 'vitest';
import { plural } from '@/lib/plural';

test.each([
  [1, 'трекер'], [2, 'трекера'], [3, 'трекера'], [5, 'трекеров'], [11, 'трекеров'], [12, 'трекеров'], [21, 'трекер'], [22, 'трекера'], [0, 'трекеров'],
])('%i', (n, w) => expect(plural(n, 'трекер', 'трекера', 'трекеров')).toBe(w));
